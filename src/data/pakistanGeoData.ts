// Helper to generate district polygon approximations around centroid for Leaflet GeoJSON
export function generateDistrictPolygon(centerLat: number, centerLng: number, radiusKm: number = 25): [number, number][] {
  const points: [number, number][] = [];
  const numSides = 10;
  // Convert km to approximate degrees
  const latDelta = radiusKm / 111.0;
  const lngDelta = radiusKm / (111.0 * Math.cos((centerLat * Math.PI) / 180));

  for (let i = 0; i <= numSides; i++) {
    const angle = (i * 2 * Math.PI) / numSides;
    // Add realistic jaggedness for natural district boundary feel
    const jitter = 0.85 + 0.3 * Math.sin(angle * 3 + centerLat);
    const lat = centerLat + latDelta * Math.sin(angle) * jitter;
    const lng = centerLng + lngDelta * Math.cos(angle) * jitter;
    points.push([lat, lng]);
  }
  return points;
}

